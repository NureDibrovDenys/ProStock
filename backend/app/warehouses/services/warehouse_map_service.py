#колекція мапи -> поле ідентифікатора її об'єктів
_ID_FIELDS = {
    "partitions": "partition_id",
    "racks": "rack_id",
    "obstacles": "obstacle_id",
    "zones": "zone_id",
    "entry_points": "point_id",
}


